def codegen_results(
    samples_list,
    generations_list,
    num_process_evaluate=16,
    timeout=6,
    debug=False,
):
    """LiveCodeBench's codegen_metrics() up to its results: every generation becomes its own evaluation task (a
    process per generation, num_process_evaluate at a time), and the per-generation results come back in input order.

    Returns (results, metadatas): results[i] is the list, in order, of the per-test result lists of the generations
    of sample i (True = test passed; -2 wrong answer, -3 time limit, -4 runtime or compile error). A harness error or
    a global timeout gives [-2] with metadata error_code -5. metadatas[i] holds the matching metadata dicts."""
    samples_linear = []
    generations_linear = []
    remap_index = []
    results = defaultdict(list)
    metadatas = defaultdict(list)
    for idx, (sample, generation_list) in enumerate(
        zip(samples_list, generations_list)
    ):
        assert isinstance(generation_list, list), generations_list[0]
        for generation in generation_list:
            assert isinstance(generation, str), generations_list[0]
            samples_linear.append(sample)
            generations_linear.append([generation])
            remap_index.append(idx)

    results_linear, metadatas_linear = evaluate_generations(
        samples_linear,
        generations_linear,
        debug=debug,
        num_process_evaluate=num_process_evaluate,
        timeout=timeout,
    )

    for idx, sub_results in sorted(results_linear.items(), key=lambda x: x[0]):
        results[remap_index[idx]].append(sub_results[0])

    for idx, sub_metadatas in sorted(metadatas_linear.items(), key=lambda x: x[0]):
        metadatas[remap_index[idx]].append(sub_metadatas[0])

    return results, metadatas
